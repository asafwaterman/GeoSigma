"""VES field sheets of the Northern Arava analysis (Paparo and Levitte 1977, GSI 05/77), Vol. 2.

Vol. 2 holds about 70 pages of field sheets, up to four per page, grouped by map and
section (index on page 3). Each sheet's CAL. RES. band gives the interpreted layered
model in ohm.m. ``extraction/ves_sheets.json`` has, per sheet, the footer (D.P. number,
file, job, coordinates, elevation), the box values and the AB/2 of the box edges, all
read by eye from 300 dpi crops (edges against the printed axis labels, about +-10 %).

This script turns them into ``extraction/ves_readings.yaml`` and runs ``build_ves``.
Coordinates are printed in units of 10 m (5 digits) or 100 m (4 digits); both are
written as 10 m units. Sites are named file-D.P. as on the index (e.g. 224-728).

Run: ``python -m geosigma.extract.arava_north``.
"""
from __future__ import annotations

import json
import re

import yaml

from ..store import SURVEYS_DIR
from .build_ves import build

SURVEY = "paparo-1977-northern-arava"
SDIR = SURVEYS_DIR / SURVEY
PDF = "Paparo-Levitte-Analysis-Northern-Arava-Electrical-Resistivity-Measurements-Vol-2-GSI-05-77-IPRG-PK-249-76-1977.pdf"


def ten_m(v: str) -> int | None:
    digits = re.sub(r"\D", "", str(v or ""))
    if len(digits) == 4:
        return int(digits) * 10
    if len(digits) in (5, 6):
        return int(digits)
    return None


def readings() -> tuple[list[dict], list[str]]:
    sheets = json.loads((SDIR / "extraction" / "ves_sheets.json").read_text())
    out, skipped, seen = [], [], set()
    for s in sorted(sheets, key=lambda s: (s["page"], s["quad"])):
        where = f"page {s['page']} {s['quad']}"
        rho, edges = s.get("rho") or [], s.get("edges_m") or []
        x, y = ten_m(s.get("x")), ten_m(s.get("y"))
        if s.get("partial") or not rho or len(edges) != len(rho) - 1 or x is None or y is None:
            skipped.append(f"{where}: {s.get('note') or 'incomplete'}")
            continue
        dp = re.sub(r"[^\w]", "", str(s.get("dp") or "")) or f"p{s['page']}{s['quad']}"
        file = re.sub(r"\D", "", str(s.get("file") or "")) or "x"
        key = f"{file}-{dp}"
        if key in seen:  # the same sounding on two sheets: keep both, apart
            dp = f"{dp}b"
        seen.add(f"{file}-{dp}")
        out.append({
            "page": s["page"], "edges_m": [float(e) for e in edges], "job": file, "dp": dp, "x": x, "y": y,
            "elev": s.get("elev"), "rho": rho, "confidence": "B" if s.get("sure", True) else "C",
            "note": " ".join(filter(None, [f"Sheet at {where} of Vol. 2; job {s.get('job') or '?'}.", s.get("note")])),
        })
    return out, skipped


def run() -> int:
    rows, skipped = readings()
    head = ("# Generated by geosigma.extract.arava_north from extraction/ves_sheets.json (read by eye).\n"
            "# Coordinates in units of 10 m; job = file number, so sites are file-D.P.\n")
    (SDIR / "extraction" / "ves_readings.yaml").write_text(
        head + yaml.safe_dump(rows, sort_keys=False, allow_unicode=True, width=140, default_flow_style=None))
    for s in skipped:
        print("SKIPPED", s)
    return build(SURVEY, PDF, "vol2")


if __name__ == "__main__":
    print(run(), "models")
